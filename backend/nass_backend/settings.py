# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

if getattr(sys, "frozen", False):
    # Installed app: store DB in a writable user location.
    app_data_dir = Path(os.getenv("LOCALAPPDATA", str(Path.home()))) / "NASS"
    app_data_dir.mkdir(parents=True, exist_ok=True)
    runtime_db_path = app_data_dir / "nass.sqlite3"

    # First run: seed from the CLEAN bundled template (already migrated).
    #
    # This deliberately points at database/seed.sqlite3 -- an empty, fully
    # migrated database containing only the default categories. It used to
    # point at database/nass.sqlite3, which is the *developer's working
    # database*, so every fresh shop install inherited the developer's items,
    # users and passwords. The dev database must never reach production.
    bundled_db_path = BASE_DIR.parent / "database" / "seed.sqlite3"
    if not runtime_db_path.exists() and bundled_db_path.exists():
        shutil.copy2(bundled_db_path, runtime_db_path)

    db_name = runtime_db_path
else:
    db_name = BASE_DIR.parent / "database" / "nass.sqlite3"

DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': db_name,
    }
}

# The central server (PythonAnywhere) uses MySQL/Postgres via env vars.
# The packaged desktop app ignores these and stays on its local SQLite.
_DB_ENGINE = os.getenv("DJANGO_DB_ENGINE", "").lower().strip()
if _DB_ENGINE:
    if _DB_ENGINE == "mysql":
        import pymysql

        pymysql.install_as_MySQLdb()
        DATABASES["default"] = {
            "ENGINE": "django.db.backends.mysql",
            "NAME": os.getenv("DJANGO_DB_NAME", "nass"),
            "USER": os.getenv("DJANGO_DB_USER", ""),
            "PASSWORD": os.getenv("DJANGO_DB_PASSWORD", ""),
            "HOST": os.getenv("DJANGO_DB_HOST", "localhost"),
            "PORT": os.getenv("DJANGO_DB_PORT", "3306"),
            "CONN_MAX_AGE": 60,
        }
    elif _DB_ENGINE == "postgres":
        DATABASES["default"] = {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.getenv("DJANGO_DB_NAME", "nass"),
            "USER": os.getenv("DJANGO_DB_USER", ""),
            "PASSWORD": os.getenv("DJANGO_DB_PASSWORD", ""),
            "HOST": os.getenv("DJANGO_DB_HOST", "localhost"),
            "PORT": os.getenv("DJANGO_DB_PORT", "5432"),
        }
    else:
        raise ImproperlyConfigured(
            f"Unknown DJANGO_DB_ENGINE '{_DB_ENGINE}'. Use 'mysql', 'postgres' or unset."
        )


